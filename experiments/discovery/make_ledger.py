def _rank(x):
    """Average ranks, ties shared. Avoids a scipy dependency in the generator."""
    x = np.asarray(x, float)
    order = np.argsort(x, kind="mergesort")
    r = np.empty(x.size, float)
    r[order] = np.arange(x.size, dtype=float)
    # average over tied groups
    xs = x[order]
    i = 0
    while i < xs.size:
        jx = i
        while jx + 1 < xs.size and xs[jx + 1] == xs[i]:
            jx += 1
        if jx > i:
            r[order[i:jx + 1]] = np.arange(i, jx + 1).mean()
        i = jx + 1
    return r


def _ord(n):
    n = int(round(n))
    if 10 <= n % 100 <= 20:
        return f"{n}th"
    return f"{n}{ {1: 'st', 2: 'nd', 3: 'rd'}.get(n % 10, 'th') }"


def _spearman(a, b):
    ra, rb = _rank(a), _rank(b)
    ra = ra - ra.mean()
    rb = rb - rb.mean()
    d = np.sqrt((ra ** 2).sum() * (rb ** 2).sum())
    return float((ra * rb).sum() / d) if d else float("nan")


