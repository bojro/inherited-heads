def _pooled(dirs):
    """Per-item (correct, trials) summed across several runs, then item bootstrap.

    Seeds are different HEAD SETS on the same 20 items, so pooling them estimates
    'a random draw from the top-100' rather than any one draw. Returns None unless
    at least one run is complete — a partial answers.jsonl must never reach here.
    """
    from collections import defaultdict
    tot = defaultdict(lambda: [0, 0])
    used = []
    for d in dirs:
        p = os.path.join(R, d)
        if not (os.path.exists(os.path.join(p, "steer_report.json"))
                and os.path.exists(os.path.join(p, "answers.jsonl"))):
            continue
        used.append(d)
        for it, (c, n) in _sci.per_item(p).items():
            tot[it][0] += c
            tot[it][1] += n
    if not used:
        return None
    items = sorted(tot)
    C = np.array([tot[i][0] for i in items], float)
    N = np.array([tot[i][1] for i in items], float)
    return C.sum() / N.sum(), C, N, used


def _bootvals(C, N, seed):
    rng = np.random.default_rng(seed)
    idx = rng.integers(0, len(C), (10000, len(C)))
    return C[idx].sum(1) / N[idx].sum(1)


